def load(results):
    pts = {}
    for f in glob.glob(os.path.join(results, "raw", "*", "*-c*.json")):
        with open(f) as fh:
            r = json.load(fh)
        pts[(r["profile"], r["system"], r["bench_scenario"], r["concurrency"])] = r
    return pts


def fmt_num(v):
    if v is None:
        return "-"
    if v >= 100000:
        return f"{v / 1000:.0f}K"
    if v >= 10000:
        return f"{v / 1000:.1f}K"
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    return f"{v:.2f}"


def fmt_ms(v):
    if v is None:
        return "-"
    if v >= 1000:
        return f"{v / 1000:.2f} s"
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    return f"{v:.2f}"


def lat(r, key, q):
    d = r.get(key) or {}
    return d.get(q)


# ---------------------------------------------------------------- tables


def tables(pts):
    out = ["# Results tables", "",
           "Generated by `bench/report.py` from `raw/`. Latencies in ms (p50/p90/p99/p99.9/max "
           "from HDR histograms over the measured window). `+p50` is the median latency added "
           "over the direct upstream at the same concurrency. CPU is the gateway's process tree "
           "(all workers) during the window, in cores and in CPU-microseconds per successful "
           "request; memory is the peak of the summed RSS of the tree and the summed PSS "
           "(shared pages split between LiteLLM's forked workers) at the end. `other load` "
           "is the busy CPUs on the rest of the machine during the point.", ""]
    profiles = sorted({p for p, *_ in pts}, key=lambda p: list(PROFILE_TITLE).index(p))
    for profile in profiles:
        out += [f"## Profile `{profile}`: {PROFILE_TITLE[profile]}", ""]
        for sc in SCENARIOS:
            rows = sorted(
                [k for k in pts if k[0] == profile and k[2] == sc],
                key=lambda k: (SYSTEMS.index(k[1]), k[3]))
            if not rows:
                continue
            stream = sc == "stream"
            out += [f"### {SCENARIO_TITLE[sc]}", ""]
            head = ["system", "conc", "req/s", "p50", "p90", "p99", "p99.9", "max"]
            if stream:
                head += ["TTFB p50", "TTFB p99"]
            head += ["+p50", "errors", "gw CPU cores", "CPU us/req", "RSS MB", "PSS MB", "other load"]
            out.append("| " + " | ".join(head) + " |")
            out.append("|" + "---|" * len(head))
            for k in rows:
                r = pts[k]
                base_sc = "chat" if sc == "db" else sc
                base = pts.get((profile, "direct", base_sc, k[3]))
                l = r.get("latency_ms") or {}
                cells = [SHORT[k[1]], str(k[3]), fmt_num(r["throughput_rps"]),
                         fmt_ms(l.get("p50")), fmt_ms(l.get("p90")), fmt_ms(l.get("p99")),
                         fmt_ms(l.get("p999")), fmt_ms(l.get("max"))]
                if stream:
                    cells += [fmt_ms(lat(r, "ttfb_ms", "p50")), fmt_ms(lat(r, "ttfb_ms", "p99"))]
                if base and k[1] != "direct" and l.get("p50") is not None and base.get("latency_ms"):
                    cells.append(f"{l['p50'] - base['latency_ms']['p50']:+.2f}")
                else:
                    cells.append("-")
                errs = r.get("errors_total", 0)
                cells.append(str(errs) if not errs else f"{errs} {r.get('errors')}")
                gw = (r.get("processes") or {}).get("gateway")
                if gw:
                    cells += [f"{gw['cpu_cores']:.2f}", f"{gw['cpu_us_per_request']:.0f}",
                              f"{gw['rss_peak_mb']:.0f}", f"{gw['pss_end_mb']:.0f}"]
                else:
                    cells += ["-", "-", "-", "-"]
                cells.append(f"{r.get('other_cpus_busy_cores', 0):.1f}")
                out.append("| " + " | ".join(cells) + " |")
            out.append("")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- charts


def log_ticks(lo, hi):
    ticks = []
    e = math.floor(math.log10(lo))
    mults = (1,) if hi / lo > 1000 else (1, 2, 5)
    while 10 ** e <= hi * 1.0001:
        for m in mults:
            v = m * 10 ** e
            if lo * 0.9999 <= v <= hi * 1.0001:
                ticks.append(v)
        e += 1
    return ticks


def tick_label(v, unit):
    if unit == "ms":
        if v >= 1000:
            return f"{v / 1000:g} s"
        return f"{v:g}"
    if v >= 1000:
        return f"{v / 1000:g}K"
    return f"{v:g}"


def line_panels(pts, profile, metric, title, subtitle, unit):
    """Small multiples (one panel per scenario), x = concurrency, log y."""
    concs = sorted({k[3] for k in pts if k[0] == profile})
    panels = [sc for sc in SCENARIOS if any(k[0] == profile and k[2] == sc for k in pts)]
    if not panels:
        return None
    pw, ph = 330, 230  # panel plot area
    ml, mr, mt, mb = 58, 112, 34, 40
    cols = 2
    rows = math.ceil(len(panels) / cols)
    W = cols * (ml + pw + mr) + 10
    systems_present = [s for s in SYSTEMS if any(k[0] == profile and k[1] == s for k in pts)]
    # Legend items wrapped to the chart width.
    legend, x, ly = [], 16, 68
    for s in systems_present:
        width = 24 + int(6.6 * len(NAMES[s])) + 22
        if x + width > W - 10:
            x, ly = 16, ly + 20
        legend.append((x, ly, s))
        x += width
    top = ly + 24
    H = top + rows * (mt + ph + mb) + 10

    def value(r):
        if metric == "throughput":
            return r["throughput_rps"] or None
        return (r.get("latency_ms") or {}).get(metric)

    o = [f'<svg xmlns="http://www.w3.org/2000/svg" class="viz" width="{W}" height="{H}" '
         f'viewBox="0 0 {W} {H}" role="img" aria-label="{escape(title)}">', STYLE,
         f'<rect class="bg" width="{W}" height="{H}" rx="8"/>',
         f'<text class="title" x="16" y="26">{escape(title)}</text>',
         f'<text class="subtitle" x="16" y="45">{escape(subtitle)}</text>']
    for x, ly, s in legend:
        o.append(f'<line x1="{x}" y1="{ly}" x2="{x + 18}" y2="{ly}" class="line" '
                 f'style="stroke:var({VAR[s]})"/>')
        o.append(f'<circle cx="{x + 9}" cy="{ly}" r="4" class="dot" style="fill:var({VAR[s]})"/>')
        o.append(f'<text class="legend" x="{x + 24}" y="{ly + 4}">{escape(NAMES[s])}</text>')

    for i, sc in enumerate(panels):
        px = (i % cols) * (ml + pw + mr) + ml
        py = top + (i // cols) * (mt + ph + mb) + mt
        vals = [value(pts[k]) for k in pts if k[0] == profile and k[2] == sc]
        vals = [v for v in vals if v]
        lo, hi = min(vals), max(vals)
        lo = 10 ** math.floor(math.log10(lo))
        hi = 10 ** math.ceil(math.log10(hi))
        if hi / lo < 10:
            hi = lo * 10

        def yy(v):
            return py + ph - (math.log10(v) - math.log10(lo)) / (math.log10(hi) - math.log10(lo)) * ph

        def xx(c):
            return px + (concs.index(c) + 0.5) / len(concs) * pw

        o.append(f'<text class="panel" x="{px}" y="{py - 12}">{escape(SCENARIO_TITLE[sc])}</text>')
        for t in log_ticks(lo, hi):
            y = yy(t)
            o.append(f'<line class="grid" x1="{px}" x2="{px + pw}" y1="{y:.1f}" y2="{y:.1f}"/>')
            o.append(f'<text class="tick" x="{px - 6}" y="{y + 4:.1f}" text-anchor="end">'
                     f'{tick_label(t, unit)}</text>')
        o.append(f'<line class="axis" x1="{px}" x2="{px + pw}" y1="{py + ph}" y2="{py + ph}"/>')
        for c in concs:
            o.append(f'<text class="tick" x="{xx(c):.1f}" y="{py + ph + 16}" text-anchor="middle">{c}</text>')
        o.append(f'<text class="label" x="{px + pw / 2}" y="{py + ph + 32}" text-anchor="middle">'
                 f'concurrent connections</text>')
        ends = []
        base_sc = "chat" if sc == "db" else sc
        for s in systems_present:
            if s == "direct" and sc == "db":
                continue  # the baseline has no database; see the chat panel
            key_sc = base_sc if s == "direct" else sc
            series = [(c, pts.get((profile, s, key_sc, c))) for c in concs]
            series = [(c, r) for c, r in series if r and value(r)]
            if not series:
                continue
            coords = [(xx(c), yy(value(r)), c, r) for c, r in series]
            d = " ".join(f"{'M' if j == 0 else 'L'}{x:.1f},{y:.1f}" for j, (x, y, _, _) in enumerate(coords))
            o.append(f'<path class="line" d="{d}" style="stroke:var({VAR[s]})"/>')
            for x, y, c, r in coords:
                l = r.get("latency_ms") or {}
                tip = (f"{NAMES[s]}, {c} connections: {fmt_num(r['throughput_rps'])} req/s, "
                       f"p50 {fmt_ms(l.get('p50'))} ms, p99 {fmt_ms(l.get('p99'))} ms")
                if r.get("errors_total"):
                    tip += f", {r['errors_total']} errors"
                o.append(f'<g><title>{escape(tip)}</title><circle class="hit" cx="{x:.1f}" cy="{y:.1f}" r="10"/>'
                         f'<circle class="dot" cx="{x:.1f}" cy="{y:.1f}" r="4" style="fill:var({VAR[s]})"/></g>')
            x, y, _, r = coords[-1]
            ends.append([y, s, value(r)])
        # End labels with leader lines when they would collide.
        ends.sort()
        placed = []
        for y, s, v in ends:
            ly = y
            if placed and ly - placed[-1] < 13:
                ly = placed[-1] + 13
            placed.append(ly)
            lx = px + pw + 8
            txt = f"{SHORT[s]} {fmt_num(v) if unit != 'ms' else fmt_ms(v)}"
            if abs(ly - y) > 1:
                o.append(f'<line class="axis" x1="{px + pw - 4}" y1="{y:.1f}" x2="{lx - 2}" y2="{ly - 4:.1f}"/>')
            o.append(f'<text class="label" x="{lx}" y="{ly:.1f}">{escape(txt)}</text>')
    o.append("</svg>")
    return "\n".join(o)


def bar_chart(pts, profile, scenario, conc, field, title, subtitle, unit_label):
    """Horizontal bars, one per system, linear axis from zero, value at the tip."""
    rows = []
    for s in SYSTEMS:
        r = pts.get((profile, s, scenario, conc))
        gw = (r or {}).get("processes", {}).get("gateway")
        if gw and gw.get(field):
            rows.append((s, gw[field]))
    if not rows:
        return None
    W, bar, gap = 760, 20, 14
    ml, mr, top = 250, 90, 70
    H = top + len(rows) * (bar + gap) + 40
    vmax = max(v for _, v in rows)
    pw = W - ml - mr
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" class="viz" width="{W}" height="{H}" '
         f'viewBox="0 0 {W} {H}" role="img" aria-label="{escape(title)}">', STYLE,
         f'<rect class="bg" width="{W}" height="{H}" rx="8"/>',
         f'<text class="title" x="16" y="26">{escape(title)}</text>',
         f'<text class="subtitle" x="16" y="45">{escape(subtitle)}</text>']
    step = 10 ** math.floor(math.log10(vmax))
    if vmax / step < 3:
        step /= 2
    t = 0
    while t <= vmax * 1.0001:
        x = ml + t / vmax * pw
        o.append(f'<line class="grid" x1="{x:.1f}" x2="{x:.1f}" y1="{top - 8}" y2="{H - 34}"/>')
        o.append(f'<text class="tick" x="{x:.1f}" y="{H - 20}" text-anchor="middle">{t:g}</text>')
        t += step
    o.append(f'<text class="label" x="{ml + pw / 2}" y="{H - 6}" text-anchor="middle">{escape(unit_label)}</text>')
    for i, (s, v) in enumerate(rows):
        y = top + i * (bar + gap)
        w = max(v / vmax * pw, 2)
        r = 4 if w > 8 else 0
        # Square at the baseline, rounded data end.
        d = (f"M{ml},{y} H{ml + w - r} Q{ml + w},{y} {ml + w},{y + r} V{y + bar - r} "
             f"Q{ml + w},{y + bar} {ml + w - r},{y + bar} H{ml} Z")
        o.append(f'<g><title>{escape(NAMES[s])}: {v:g} {escape(unit_label)}</title>'
                 f'<path d="{d}" style="fill:var({VAR[s]})"/></g>')
        o.append(f'<text class="legend" x="{ml - 10}" y="{y + bar / 2 + 4}" text-anchor="end">{escape(NAMES[s])}</text>')
        o.append(f'<text class="label" x="{ml + w + 6}" y="{y + bar / 2 + 4}">{v:g}</text>')
    o.append(f'<line class="axis" x1="{ml}" x2="{ml}" y1="{top - 8}" y2="{H - 34}"/>')
    o.append("</svg>")
    return "\n".join(o)


def main():
    results = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "results")
    pts = load(results)
    if not pts:
        sys.exit(f"no results under {results}/raw")
    with open(os.path.join(results, "tables.md"), "w") as f:
        f.write(tables(pts))
    written = ["tables.md"]
    for profile in PROFILE_TITLE:
        for metric, name, title, unit in (
            ("throughput", "throughput", "Throughput (successful requests/s, log scale)", "rps"),
            ("p50", "latency-p50", "Median latency (ms, log scale)", "ms"),
            ("p99", "latency-p99", "p99 latency (ms, log scale)", "ms"),
        ):
            svg = line_panels(pts, profile, metric, title,
                              f"Profile {profile}: {PROFILE_TITLE[profile]}. Gateway pinned to 8 cores.", unit)
            if svg:
                fn = f"{name}-{profile}.svg"
                with open(os.path.join(results, fn), "w") as f:
                    f.write(svg)
                written.append(fn)
    for profile, sc, conc in (("lat0", "chat", 64), ("lat0", "db", 64)):
        svg = bar_chart(pts, profile, sc, conc, "cpu_us_per_request",
                        f"Gateway CPU per request: {SCENARIO_TITLE[sc].lower()}",
                        f"Profile {profile}, {conc} connections; all gateway processes, user + system time.",
                        "CPU microseconds per request")
        if svg:
            fn = f"cpu-per-request-{sc}-{profile}.svg"
            with open(os.path.join(results, fn), "w") as f:
                f.write(svg)
            written.append(fn)
    svg = bar_chart(pts, "lat0", "chat", 64, "pss_end_mb", "Gateway memory (PSS)",
                    "Profile lat0, chat, 64 connections; proportional set size summed over all processes.",
                    "MB")
    if svg:
        with open(os.path.join(results, "memory-pss.svg"), "w") as f:
            f.write(svg)
        written.append("memory-pss.svg")
    print("wrote " + ", ".join(written))


if __name__ == "__main__":
    main()
